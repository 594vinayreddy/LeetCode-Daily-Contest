class Solution(object):
    def countCommas(self, n):
        if n < 999:
            return 0
        elif n <= 999999:
            return n - 999
        elif n <= 999999999:
            return 999000 + 2 * (n - 999999)
        elif n <= 999999999999:
            return 999000 + (2 * 999000000) + 3 * (n - 999999999)
        elif n <= 999999999999999:
            return 999000 + (2 * 999000000) + (3 * 999000000000) + 4 * (n - 999999999999)
        else:
            return (999000 + (2 * 999000000) + (3 * 999000000000)
                    + (4 * 999000000000000) + 5 * (n - 999999999999999))